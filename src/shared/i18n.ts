/**
 * Interface language: Russian or English. The Russian text is the key — `t('Порт {port} занят', { port })` —
 * and EN holds its English. `npm test` fails if a Russian string in the code has no English, so nothing
 * stays untranslated. Main and renderer each keep their own current language; the renderer asks main at start.
 */

export type Lang = 'ru' | 'en'
export type LangSetting = Lang | 'system'

let current: Lang = 'en'

export function setLang(lang: Lang): void {
  current = lang
}

export function getLang(): Lang {
  return current
}

/** The setting wins; «system» follows the OS (Russian for ru-*, English otherwise). */
export function resolveLang(setting: LangSetting | undefined, systemLocale: string): Lang {
  if (setting === 'ru' || setting === 'en') return setting
  return /^ru\b/i.test(systemLocale) ? 'ru' : 'en'
}

type Params = Record<string, string | number | null | undefined>

export function t(text: string, params?: Params): string {
  const template = current === 'en' ? (EN[text] ?? text) : text
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (whole, key: string) => (key in params ? String(params[key] ?? '') : whole))
}

/** «3 сайта» / «3 sites». */
export function sitesWord(n: number): string {
  if (current === 'en') return `${n} ${n === 1 ? 'site' : 'sites'}`
  const mod10 = n % 10
  const mod100 = n % 100
  const word =
    mod10 === 1 && mod100 !== 11 ? 'сайт' : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14) ? 'сайта' : 'сайтов'
  return `${n} ${word}`
}

/** For sorting names the way the reader expects. */
export const collator = (): Intl.Collator => new Intl.Collator(current === 'ru' ? 'ru' : 'en', { numeric: true })

